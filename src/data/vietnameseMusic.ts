export function getSongCoverUrl(song?: SongItem | null): string {
  if (!song) {
    return 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=400&auto=format&fit=crop&q=80';
  }
  if (song.coverUrl) return song.coverUrl;
  if (song.youtubeId) {
    return `https://i.ytimg.com/vi/${song.youtubeId}/hqdefault.jpg`;
  }
  if (song.id === 'romantic-piano') {
    return 'https://images.unsplash.com/photo-1520523839898-50712743e9a7?w=400&auto=format&fit=crop&q=80';
  }
  if (song.id === 'music-box') {
    return 'https://images.unsplash.com/photo-1513883049090-d0b7439799bf?w=400&auto=format&fit=crop&q=80';
  }
  if (song.id === 'spring-acoustic') {
    return 'https://images.unsplash.com/photo-1510915361894-db8b60106cb1?w=400&auto=format&fit=crop&q=80';
  }
  if (song.id === 'cosmic-ambient') {
    return 'https://images.unsplash.com/photo-1506703719100-a0f3a48c0f86?w=400&auto=format&fit=crop&q=80';
  }
  return 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=400&auto=format&fit=crop&q=80';
}
